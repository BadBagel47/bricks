// Builds docs/music/player.html: one self-contained owner test page with the
// game theme (bundled from src/audio) and every proposal in docs/music/themes.
// Usage: npm run music:player
import { build } from 'esbuild'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const music = join(root, 'docs/music')
const bundle = await build({ entryPoints: [join(root, 'src/music-player/main.ts')], bundle: true, write: false, format: 'iife', target: 'es2022', minify: true, legalComments: 'none' })
const themes = readdirSync(join(music, 'themes')).filter((name) => name.endsWith('.js')).sort()
const inline = (code) => code.replace(/<\/script/gi, '<\\/script')
const scripts = [readFileSync(join(music, 'engine.js'), 'utf8'), ...themes.map((name) => readFileSync(join(music, 'themes', name), 'utf8'))]
const style = readFileSync(join(root, 'src/music-player/style.css'), 'utf8')

const html = `<!DOCTYPE html>
<html lang="sv">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="theme-color" content="#0E1120">
<title>Bricks – musik</title>
<!-- Generated by scripts/build-music-player.mjs from src/music-player and docs/music. Do not edit by hand. -->
<style>${style}</style>
</head>
<body>
<main>
  <header><span class="brand" aria-label="Bricks">${[...'BRICKS'].map((letter) => `<span class="brand-tile" aria-hidden="true">${letter}</span>`).join('')}</span><h1>MUSIK</h1></header>
  <section class="card" aria-labelledby="now-title">
    <div class="now">
      <button id="play" class="play" type="button" aria-label="Spela"><svg class="play-icon" aria-hidden="true" width="34" height="34" viewBox="0 0 24 24" fill="currentColor"><path d="M8 5.5v13a1 1 0 0 0 1.5.86l10.5-6.5a1 1 0 0 0 0-1.72L9.5 4.64A1 1 0 0 0 8 5.5z"/></svg><svg class="stop-icon" aria-hidden="true" width="30" height="30" viewBox="0 0 24 24" fill="currentColor"><rect x="6" y="6" width="12" height="12" rx="2"/></svg></button>
      <div class="now-text"><span id="now-chip" class="chip"></span><h3 id="now-title"></h3><span id="now-tempo" class="tempo"></span><p id="now-desc"></p></div>
      <div class="controls">
        <div id="danger-row" class="control"><span id="danger-label">Fara</span><button id="danger" class="switch" type="button" role="switch" aria-checked="false" aria-labelledby="danger-label"></button></div>
        <div id="level-row" class="control" hidden><span>Nivå</span><div class="stepper"><button id="level-down" type="button" aria-label="Sänk nivå">−</button><output id="level-value">00</output><button id="level-up" type="button" aria-label="Höj nivå">+</button></div></div>
        <label class="control"><span>Volym</span><input id="volume" type="range" min="0" max="1" step="0.05" value="0.8"></label>
        <div class="control"><span>Tempo</span><div class="bpm"><i id="beat" class="beat" aria-hidden="true"></i><strong id="bpm">–</strong><small>BPM</small></div></div>
      </div>
    </div>
  </section>
  <section class="card" aria-label="Tidslinje">
    <h2>Tidslinje</h2>
    <div class="timeline"><div id="labels" class="labels"></div><div id="scroll" class="scroll"><canvas id="base"></canvas><canvas id="overlay"></canvas></div></div>
    <p class="hint">Hela slingan. Lamporna lyser när instrumentet spelar. Med Fara på visas fara-versionen.</p>
  </section>
  <section class="card side" aria-labelledby="rank-title">
    <h2 id="rank-title">Rangordning</h2>
    <ol id="rank" class="rank"></ol>
    <div class="copy-row"><button id="copy" type="button">Kopiera rangordning</button><span id="copied" role="status"></span></div>
    <p class="hint">Tryck på en låt för att välja den. Ordningen sparas i den här webbläsaren.</p>
  </section>
</main>
${scripts.map((code) => `<script>${inline(code)}</script>`).join('\n')}
<script>${inline(bundle.outputFiles[0].text)}</script>
</body>
</html>
`
writeFileSync(join(music, 'player.html'), html)
console.log(`docs/music/player.html: ${themes.length} proposal files + game theme, ${Math.round(html.length / 1024)} kB`)
